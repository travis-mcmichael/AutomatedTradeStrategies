using System.Diagnostics;
using System.Text.Json;
using Microsoft.AspNetCore.Mvc;
using AutomatedTradeStrategies.Management.Web.Models;
using AutomatedTradeStrategies.Management.Web.Services;
using AutomatedTrading.Core.Data;
using AutomatedTrading.Core.Data.Commands;
using AutomatedTrading.Core.Data.Queries;
using AutomatedTrading.Core.Framework;
using AutomatedTrading.Core.Import;
using AutomatedTrading.Core.Models;

namespace AutomatedTradeStrategies.Management.Web.Controllers.Application;

public class HomeController(
    ILogger<HomeController> logger,
    GetAllModelConfigs allModelConfigs,
    IDefaultUpdateCommand<ModelConfig> updateModelConfig,
    ReplaceModelFeatureParams replaceModelFeatureParams,
    FeatureExportJobs featureExportJobs,
    GetBarDataCountsByDate barDataCountsByDate,
    GetDistinctBarDataInstruments distinctBarDataInstruments,
    IDefaultInsertCommand<BarData> barInsertCommand) : Controller
{
    public IActionResult Index()
    {
        return View();
    }

    public async Task<IActionResult> Models()
    {
        var result = (await allModelConfigs.Execute()).OrderBy(m => m.ModelName);

        // featuresExported isn't a ModelConfig column (the generic data layer would try to read/write it),
        // so it's added to each model's JSON here. NormalizePath maps /mnt/c/... to C:\... when running on Windows.
        var rows = result.Select(m =>
        {
            var row = JsonSerializer.SerializeToNode(m, JsonSerializerOptions.Web)!.AsObject();
            row["featuresExported"] = !string.IsNullOrWhiteSpace(m.FeatureLocation)
                && System.IO.File.Exists(Path.Combine(Operations.NormalizePath(m.FeatureLocation), "features.csv"));
            return row;
        });
        return Ok(rows);
    }

    // Updates only the ModelConfig row's own columns (FeatureLocation/OutputLocation are generated by the
    // edit screen from appsettings). Deliberately not UpdateModelConfig, which deletes and re-inserts the
    // model's features/params from the payload (empty here).
    [HttpPost]
    public async Task<IActionResult> UpdateModel([FromBody] ModelConfig model)
    {
        if (model.Id <= 0)
            return BadRequest("A model Id is required.");
        // Version is set by a successful feature export (FeatureExportJobs), never by the edit screen.
        ModelState.Remove(nameof(ModelConfig.Version));
        if (!ModelState.IsValid)
            return BadRequest(string.Join(" ", ModelState.Values.SelectMany(v => v.Errors).Select(e => e.ErrorMessage)));

        var updated = await updateModelConfig.Execute(new
        {
            model.ModelName,
            model.Instrument,
            model.Target,
            model.BarType,
            model.WindowStart,
            model.WindowEnd,
            model.TrainingStart,
            model.TrainingEnd,
            model.FeatureLocation,
            model.OutputLocation,
            model.Active,
            model.Export
        }, new { model.Id });
        return updated == 0 ? NotFound($"Model {model.Id} was not found.") : Ok();
    }

    // Replaces all of a model's feature param values with the posted set and saves the feature names.
    [HttpPost]
    public async Task<IActionResult> UpdateFeatureParams([FromBody] ModelFeatureParamsUpdate request)
    {
        if (request.ModelConfigId <= 0)
            return BadRequest("A model Id is required.");

        try
        {
            if (request.Features.GroupBy(f => f.ModelFeatureId).Any(g => g.Count() > 1))
                return BadRequest("A feature name was sent more than once for the same feature.");

            await replaceModelFeatureParams.Execute(request.ModelConfigId, request.Params,
                request.Features.ToDictionary(f => f.ModelFeatureId, f => f.ModelFeatureName));
            return Ok();
        }
        catch (ArgumentException ex)
        {
            return BadRequest(ex.Message);
        }
    }

    // Starts a background feature export for the model (or returns the one already running).
    [HttpPost]
    public IActionResult ExportFeatures(long id)
    {
        if (id <= 0)
            return BadRequest("A model Id is required.");
        return Ok(featureExportJobs.Start(id));
    }

    public IActionResult ExportFeaturesStatus(long id)
    {
        var status = featureExportJobs.GetStatus(id);
        return status is null ? NotFound($"No feature export has been started for model {id}.") : Ok(status);
    }

    public async Task<IActionResult> BarDataCounts()
    {
        var result = await barDataCountsByDate.Execute();
        return Ok(result);
    }

    public async Task<IActionResult> Instruments()
    {
        var result = await distinctBarDataInstruments.Execute();
        return Ok(result);
    }

    [HttpPost]
    public async Task<IActionResult> ImportBarData(List<IFormFile> files)
    {
        if (files == null || files.Count == 0)
            return BadRequest("No files were uploaded.");

        var results = new List<object>();
        foreach (var file in files)
        {
            var tempPath = Path.GetTempFileName();
            try
            {
                await using (var stream = System.IO.File.Create(tempPath))
                    await file.CopyToAsync(stream);

                var imported = await BarImporter.ImportBarData(tempPath, file.FileName, barInsertCommand);
                results.Add(new { fileName = file.FileName, imported });
            }
            catch (FormatException ex)
            {
                results.Add(new { fileName = file.FileName, imported = 0, error = ex.Message });
            }
            finally
            {
                System.IO.File.Delete(tempPath);
            }
        }

        return Ok(results);
    }

    public IActionResult Privacy()
    {
        return View();
    }

    [ResponseCache(Duration = 0, Location = ResponseCacheLocation.None, NoStore = true)]
    public IActionResult Error()
    {
        return View(new ErrorViewModel { RequestId = Activity.Current?.Id ?? HttpContext.TraceIdentifier });
    }
}
