using System.Diagnostics;
using Microsoft.AspNetCore.Mvc;
using AutomatedTradeStrategies.Management.Web.Models;
using AutomatedTradeStrategies.Management.Web.Services;
using AutomatedTrading.Core.Data;
using AutomatedTrading.Core.Data.Commands;
using AutomatedTrading.Core.Data.Queries;
using AutomatedTrading.Core.Framework;
using AutomatedTrading.Core.Import;
using AutomatedTrading.Core.Models;

namespace AutomatedTradeStrategies.Management.Web.Controllers.Application;

public class HomeController(
    ILogger<HomeController> logger,
    GetAllModelConfigs allModelConfigs,
    IDefaultRepository<ModelConfig> models,
    GetFeatureTypes featureTypes,
    IDefaultRepository<FeatureTypeParam> featureTypeParams,
    IDefaultUpdateCommand<ModelConfig> updateModelConfig,
    IDefaultInsertCommand<ModelConfig> insertModelConfig,
    ReplaceModelFeatureParams replaceModelFeatureParams,
    DeleteModelConfig deleteModelConfig,
    FeatureExportJobs featureExportJobs,
    TrainingJobs trainingJobs,
    GetBarDataCountsByDate barDataCountsByDate,
    GetBarsByInstrumentSession barsByInstrumentSession,
    GetVersionChangeovers versionChangeovers,
    GetInferenceReadiness inferenceReadiness,
    IDefaultInsertCommand<BarData> barInsertCommand) : Controller
{
    public IActionResult Index()
    {
        return View();
    }

    public async Task<IActionResult> Models()
    {
        var result = (await allModelConfigs.Execute()).OrderBy(m => m.ModelName);
        return Ok(result);
    }

    // Model list for the Predictions tab. Readiness is not checked here; it is checked per model on demand (ModelReadiness).
    public async Task<IActionResult> Predictions()
    {
        var sessionDate = TradingCalendar.SessionDateFor(MarketTime.FromUtc(DateTime.UtcNow));
        var rows = (await models.GetDataAsync(new Dictionary<string, object> { { "1", 1 } }))
            .OrderBy(m => m.ModelName)
            .Select(m => new { id = m.Id, modelName = m.ModelName });
        return Ok(new { sessionDate = sessionDate.ToString("yyyy-MM-dd"), models = rows });
    }

    // Inference readiness of one model for the current session (see GetInferenceReadiness).
    public async Task<IActionResult> ModelReadiness(long id)
    {
        var sessionDate = TradingCalendar.SessionDateFor(MarketTime.FromUtc(DateTime.UtcNow));
        var readiness = await inferenceReadiness.Execute(id, sessionDate);
        return Ok(new
        {
            sessionDate = sessionDate.ToString("yyyy-MM-dd"),
            isReady = readiness.IsReady,
            modelIssues = readiness.Issues,
            features = readiness.Features.Select(f => new
            {
                id = f.ModelFeatureId,
                name = f.Name,
                featureTypeName = f.FeatureTypeName,
                source = f.Source,
                isReady = f.IsReady,
                issues = f.Issues
            })
        });
    }

    // Updates only the ModelConfig row's own columns (FeatureLocation/OutputLocation are generated by the
    // edit screen from appsettings). Deliberately not UpdateModelConfig, which deletes and re-inserts the
    // model's features/params from the payload (empty here).
    [HttpPost]
    public async Task<IActionResult> UpdateModel([FromBody] ModelConfig model)
    {
        if (model.Id <= 0)
            return BadRequest("A model Id is required.");
        // Version is set by a successful feature export (FeatureExportJobs), never by the edit screen.
        ModelState.Remove(nameof(ModelConfig.Version));
        if (!ModelState.IsValid)
            return BadRequest(string.Join(" ", ModelState.Values.SelectMany(v => v.Errors).Select(e => e.ErrorMessage)));

        if (await isDuplicateName(model))
            return BadRequest($"A model named '{model.ModelName}' already exists.");

        var updated = await updateModelConfig.Execute(new
        {
            model.ModelName,
            model.Instrument,
            model.Target,
            model.WindowStart,
            model.WindowEnd,
            model.TrainingStart,
            model.TrainingEnd,
            model.FeatureLocation,
            model.OutputLocation,
            model.Active,
            model.Export
        }, new { model.Id });
        return updated == 0 ? NotFound($"Model {model.Id} was not found.") : Ok();
    }

    // Creates a model with no features. Version starts empty and is set by its first successful feature export.
    [HttpPost]
    public async Task<IActionResult> CreateModel([FromBody] ModelConfig model)
    {
        ModelState.Remove(nameof(ModelConfig.Version));
        if (!ModelState.IsValid)
            return BadRequest(string.Join(" ", ModelState.Values.SelectMany(v => v.Errors).Select(e => e.ErrorMessage)));

        model.Id = 0;
        model.Version = "";
        if (await isDuplicateName(model))
            return BadRequest($"A model named '{model.ModelName}' already exists.");

        var id = await insertModelConfig.Execute(model);
        return Ok(new { id });
    }

    // ModelName is UNIQUE in ModelConfig; checked up front for a readable error instead of a constraint failure.
    private async Task<bool> isDuplicateName(ModelConfig model) =>
        (await models.GetDataAsync(new Dictionary<string, object> { { nameof(ModelConfig.ModelName), model.ModelName } }))
            .Any(m => m.Id != model.Id);

    // Replaces all of a model's feature param values with the posted set, saves the feature names, adds any
    // new features and deletes any removed ones.
    [HttpPost]
    public async Task<IActionResult> UpdateFeatureParams([FromBody] ModelFeatureParamsUpdate request)
    {
        if (request.ModelConfigId <= 0)
            return BadRequest("A model Id is required.");

        try
        {
            if (request.Features.GroupBy(f => f.ModelFeatureId).Any(g => g.Count() > 1))
                return BadRequest("A feature name was sent more than once for the same feature.");

            await replaceModelFeatureParams.Execute(request.ModelConfigId, request.Params,
                request.Features.ToDictionary(f => f.ModelFeatureId, f => f.ModelFeatureName),
                request.DeletedFeatureIds,
                request.NewFeatures);
            return Ok();
        }
        catch (ArgumentException ex)
        {
            return BadRequest(ex.Message);
        }
    }

    // Deletes the model with its features, feature params and performance rows (see DeleteModelConfig).
    [HttpPost]
    public async Task<IActionResult> DeleteModel(long id)
    {
        if (id <= 0)
            return BadRequest("A model Id is required.");
        if (featureExportJobs.GetStatus(id)?.State == FeatureExportState.Running)
            return Conflict("This model's features are being exported. Wait for the export to finish before deleting it.");

        return await deleteModelConfig.Execute(id) ? Ok() : NotFound($"Model {id} was not found.");
    }

    // Starts a background feature export for the model (or returns the one already running).
    [HttpPost]
    public IActionResult ExportFeatures(long id)
    {
        if (id <= 0)
            return BadRequest("A model Id is required.");
        return Ok(featureExportJobs.Start(id));
    }

    public IActionResult ExportFeaturesStatus(long id)
    {
        var status = featureExportJobs.GetStatus(id);
        return status is null ? NotFound($"No feature export has been started for model {id}.") : Ok(status);
    }

    // Starts Scripts/mlpipeline.sh for the model (or returns the training already running). Training reads the
    // features exported for the model's Version, so the model needs a Version first.
    [HttpPost]
    public async Task<IActionResult> TrainModel(long id)
    {
        if (id <= 0)
            return BadRequest("A model Id is required.");
        var model = (await allModelConfigs.Execute()).FirstOrDefault(m => m.Id == id);
        if (model is null)
            return NotFound($"Model {id} was not found.");
        if (string.IsNullOrWhiteSpace(model.Version))
            return BadRequest("Export the features for this model before training it.");
        if (featureExportJobs.GetStatus(id)?.State == FeatureExportState.Running)
            return Conflict("This model's features are being exported. Wait for the export to finish before training it.");

        return Ok(trainingJobs.Start(model));
    }

    public IActionResult TrainModelStatus(long id)
    {
        var status = trainingJobs.GetStatus(id);
        return status is null ? NotFound($"No training has been started for model {id}.") : Ok(status);
    }

    public async Task<IActionResult> FeatureTypes()
    {
        var result = await featureTypes.Execute();
        return Ok(result);
    }

    // The optional window fields: FeatureTypeParams that belong to no FeatureType.
    public async Task<IActionResult> WindowParams()
    {
        var result = await featureTypeParams.GetDataAsync(
            new Dictionary<string, object> { { nameof(FeatureTypeParam.FeatureTypeId), AppConstants.WINDOW_FEATURE_TYPE_ID } });
        return Ok(result);
    }

    // Defaults to the current month.
    public async Task<IActionResult> BarDataCounts(int? year, int? month)
    {
        var y = year ?? DateTime.Today.Year;
        var m = month ?? DateTime.Today.Month;
        if (m is < 1 or > 12 || y is < 1900 or > 9999)
            return BadRequest("Month must be 1-12 and year a four-digit year.");

        var result = await barDataCountsByDate.Execute(y, m);

        // Changeover dates depend on the full volume history, so search all of it, not just this month.
        var changeoverDates = new HashSet<string>();
        foreach (var instrument in result.SelectMany(r => r.Details).Select(d => d.Instrument).Distinct())
        {
            foreach (var c in await versionChangeovers.Execute(instrument, new DateTime(2000, 1, 1), DateTime.Today))
                changeoverDates.Add(c.SessionDate);
        }
        foreach (var row in result)
            row.HasChangeover = changeoverDates.Contains(row.SessionDate);

        return Ok(result);
    }

    public async Task<IActionResult> BarDataBySession(string sessionDate, string instrument, string instrumentVersion)
    {
        if (string.IsNullOrWhiteSpace(sessionDate) || string.IsNullOrWhiteSpace(instrument) || string.IsNullOrWhiteSpace(instrumentVersion))
            return BadRequest("sessionDate, instrument and instrumentVersion are required.");

        var result = await barsByInstrumentSession.Execute(sessionDate, instrument, instrumentVersion);
        return Ok(result);
    }

    [HttpPost]
    public async Task<IActionResult> PreviewBarImport(List<IFormFile> files)
    {
        if (files == null || files.Count == 0)
            return BadRequest("No files were uploaded.");

        var results = new List<object>();
        foreach (var file in files)
        {
            var tempPath = Path.GetTempFileName();
            try
            {
                await using (var stream = System.IO.File.Create(tempPath))
                    await file.CopyToAsync(stream);

                var bars = await BarImporter.ParseBarData(tempPath, file.FileName);
                var sessions = bars
                    .GroupBy(b => b.SessionDate)
                    .OrderBy(g => g.Key)
                    .Select(g => new { sessionDate = g.Key, count = g.Count() })
                    .ToList();
                results.Add(new { fileName = file.FileName, sessions });
            }
            catch (FormatException ex)
            {
                results.Add(new { fileName = file.FileName, sessions = Array.Empty<object>(), error = ex.Message });
            }
            finally
            {
                System.IO.File.Delete(tempPath);
            }
        }

        return Ok(results);
    }

    [HttpPost]
    public async Task<IActionResult> ImportBarData(List<IFormFile> files)
    {
        if (files == null || files.Count == 0)
            return BadRequest("No files were uploaded.");

        var results = new List<object>();
        foreach (var file in files)
        {
            var tempPath = Path.GetTempFileName();
            try
            {
                await using (var stream = System.IO.File.Create(tempPath))
                    await file.CopyToAsync(stream);

                var imported = await BarImporter.ImportBarData(tempPath, file.FileName, barInsertCommand);
                results.Add(new { fileName = file.FileName, imported });
            }
            catch (FormatException ex)
            {
                results.Add(new { fileName = file.FileName, imported = 0, error = ex.Message });
            }
            finally
            {
                System.IO.File.Delete(tempPath);
            }
        }

        return Ok(results);
    }

    public IActionResult Privacy()
    {
        return View();
    }

    [ResponseCache(Duration = 0, Location = ResponseCacheLocation.None, NoStore = true)]
    public IActionResult Error()
    {
        return View(new ErrorViewModel { RequestId = Activity.Current?.Id ?? HttpContext.TraceIdentifier });
    }
}
